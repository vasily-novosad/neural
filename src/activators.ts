/**
 * Функции активации и их производные.
 *
 * Активация — нелинейность после линейной части нейрона: a = f(z).
 * Без неё любая стопка слоёв схлопнулась бы в один линейный слой
 * (произведение матриц — тоже матрица), и сеть не смогла бы решить даже XOR.
 */

export interface Activation {
  // Сама функция: z → a (поэлементно, кроме softmax)
  fn: (z: number[]) => number[];

  /**
   * Производная da/dz, посчитанная поэлементно в точке z.
   *
   * Обратите внимание: аргумент — именно z (до активации), а не a.
   * У softmax её нет (см. ниже), поэтому поле необязательное.
   */
  derivative?: (z: number[]) => number[];
}

export type ActivationName = 'sigmoid' | 'relu' | 'softmax';

/**
 * Сигмоида: σ(z) = 1 / (1 + e^(−z)), значения в (0, 1).
 *
 * Производная выражается через саму функцию: σ'(z) = σ(z) · (1 − σ(z)).
 * Её максимум — 0.25 при z = 0, а при больших |z| она почти ноль. Поэтому в глубоких
 * сетях градиент, проходя через много сигмоид, затухает («затухающий градиент»).
 * Из-за этого в скрытых слоях её почти вытеснила ReLU.
 */
const sigmoidFn = (z: number[]): number[] => z.map(v => 1 / (1 + Math.exp(-v)));

const sigmoid: Activation = {
  fn: sigmoidFn,
  derivative: z => sigmoidFn(z).map(s => s * (1 - s)),
};

/**
 * ReLU: max(0, z).
 *
 * Производная равна 1 при z > 0 и 0 при z < 0 (в точке 0 её принято брать равной 0).
 * Градиент не затухает, и считается она очень дёшево. Минус: если нейрон «ушёл» в z < 0
 * на всех примерах, градиент через него всегда ноль, и он больше не учится («мёртвый нейрон»).
 */
const relu: Activation = {
  fn: z => z.map(v => Math.max(0, v)),
  derivative: z => z.map(v => (v > 0 ? 1 : 0)),
};

/**
 * Softmax: a_i = e^(z_i) / Σ_k e^(z_k). Превращает вектор в распределение вероятностей:
 * все значения в (0, 1), сумма равна 1.
 *
 * Вычитание максимума ничего не меняет математически (сокращается в числителе
 * и знаменателе), но спасает от переполнения: e^1000 = Infinity.
 *
 * Производной здесь нет намеренно. Каждый выход softmax зависит от всех входов,
 * поэтому её производная — не вектор, а матрица Якоби. Поэлементное умножение,
 * которым мы пользуемся для остальных активаций, к ней неприменимо.
 * Но softmax почти всегда стоит в паре с кросс-энтропией, а у этой пары градиент
 * по z сокращается до очень простого вида: (a − target). Этот случай разобран
 * в network.ts, в методе outputDelta.
 */
const softmax: Activation = {
  fn: z => {
    const max = Math.max(...z);
    const exps = z.map(v => Math.exp(v - max));
    const sum = exps.reduce((a, b) => a + b, 0);

    return exps.map(v => v / sum);
  },
};

export const getActivation = (name: ActivationName): Activation => {
  switch (name) {
    case 'sigmoid':
      return sigmoid;
    case 'relu':
      return relu;
    case 'softmax':
      return softmax;
    default:
      throw new Error(`Неизвестная функция активации: ${name}`);
  }
};
